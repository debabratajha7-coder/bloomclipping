def _norm(word):
    """Spelling variants of the same Devanagari word compare equal."""
    for a, b in (('़', ''), ('ऑ', 'ओ'), ('ॉ', 'ो'), ('ऍ', 'ए'), ('ॅ', 'े'), ('ँ', 'ं')):
        word = word.replace(a, b)
    return word


def _load():
    table = {}
    for line in LOANWORDS_TEXT.strip().splitlines():
        parts = line.split(None, 1)
        if len(parts) == 2:
            table[_norm(parts[0])] = parts[1].strip()
    return table


LOANWORDS = _load()
# words that are Hindi first and must keep their Hindi spelling even though they look like English loans
KEEP_HINDI = {_norm(w) for w in ('इन', 'इन्', 'सर', 'आउट', 'बस', 'ना', 'पर', 'मिस', 'हाय', 'ओह', 'वाओ')}


SUFFIXES = (('वालों', 'walon'), ('वाले', 'wale'), ('वाला', 'wala'), ('वाली', 'wali'), ('ों', 's'), ('ें', 's'))


def english_for(word):
    """The English spelling of a Devanagari loanword, or None. Understands Hindi endings: पुलिसवाले -> police wale, फोनों -> phones."""
    key = _norm(word)
    if key in KEEP_HINDI and key not in ('सर', 'हाय', 'ओह', 'वाओ'):
        return None
    found = LOANWORDS.get(key)
    if found:
        return found
    for suffix, roman in SUFFIXES:
        suffix = _norm(suffix)
        if key.endswith(suffix) and len(key) > len(suffix) + 1:
            stem = LOANWORDS.get(key[:-len(suffix)])
            if stem:
                return stem + roman if roman == 's' else stem + ' ' + roman
    return None
